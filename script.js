const container = document.getElementById("routes");

routes.forEach((route, index) => {

    const card = document.createElement("div");
    card.className = "route-card";

    const mapDiv = document.createElement("div");
    mapDiv.className = "map-container";
    mapDiv.id = "map" + index;

    const descriptionDiv = document.createElement("div");
    descriptionDiv.className = "route-description";

    descriptionDiv.innerHTML = `
        <h2>${route.title}</h2>
        <p>${route.description}</p>
        <div class="speed-control">
            <label for="speed${index}">Rider Speed (km/h):</label>
            <input type="number" id="speed${index}" value="15" min="5" max="50" step="1">
        </div>
        <div class="route-stats" id="stats${index}"></div>
        <a href="${route.file}" download class="download-btn">Download GPX</a>
    `;

    card.appendChild(mapDiv);
    card.appendChild(descriptionDiv);
    container.appendChild(card);

    const map = L.map(mapDiv.id, {
        zoomControl: false,
        attributionControl: false
    });

    L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png').addTo(map);

    new L.GPX(route.file, {
        async: true,
        polyline_options: {
            color: '#000',
            weight: 6,
            opacity: 0.9
        }
    }).on('loaded', function(e) {

        map.fitBounds(e.target.getBounds());

        const distance = (e.target.get_distance() / 1000).toFixed(2);
        const elevation = e.target.get_elevation_gain().toFixed(0);

        // Function to calculate and update time based on speed
        const updateTime = () => {
            const speed = parseFloat(document.getElementById("speed" + index).value) || 15;
            const time = (distance / speed).toFixed(2);
            document.getElementById("stats" + index).innerHTML = `
                <div>Distance: ${distance} km</div>
                <div>Elevation Gain: ${elevation} m</div>
                <div>Estimated Time: ${time} hrs</div>
            `;
        };

        // Initial display
        updateTime();

        // Update time when speed changes
        document.getElementById("speed" + index).addEventListener('input', updateTime);

    }).addTo(map);
});
